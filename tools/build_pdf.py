"""Build the English PDF of a book with Typst.

Reads the translated segments (translations/<slug>/NN.en.md), the source
segment styles (work/<slug>/chapters/NN.json) and line geometry
(NN.layout.json), and the book's "pdf" settings in config/books/<slug>.json.
The text is reflowed (English is shorter than Portuguese), reproducing the
original page size, margins, fonts, sizes, indents, spacing and footnotes.

Front matter (chapter 00) is laid out with the original vertical positions;
every other chapter starts on a new page when it did so in the original.

Output (output/<slug>/):
  <slug>-en.pdf      the book
  build/book.typ     generated Typst source (for inspection)

Usage:
  python tools/build_pdf.py <slug>
  python tools/build_pdf.py <slug> --draft    (build even if QA has errors)
"""

import argparse
import re
import sys

from common import (
    ROOT, WORK_DIR, TRANSLATIONS_DIR, PipelineError, chapter_ids, fail,
    load_book_config, load_json, parse_marked_md, strip_markup, write_text_atomic,
)
from qa import check_chapter, forms_regex, load_glossary

GLOSSARY_INTRO = (
    "This glossary was added to the English edition and is not part of the "
    "Portuguese original. It lists the author’s key concepts that appear in "
    "this book, with the original Portuguese term and the English rendering used "
    "throughout the translation."
)

OUTPUT_DIR = ROOT / "output"
FONT_MAP: dict = {}
TOKEN_RE = re.compile(r"(<i>|</i>|<b>|</b>|\[\^\d+\]|\n)")


def s(text: str) -> str:
    """A Typst string literal; inserted as plain text, no markup parsing."""
    return '#"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def inline(text: str, footnotes: dict, used: set) -> str:
    """Convert segment markup (<i>, <b>, [^n], newlines) to Typst content."""
    out = []
    for tok in TOKEN_RE.split(text):
        if not tok:
            continue
        if tok == "<i>":
            out.append("#emph[")
        elif tok == "<b>":
            out.append("#strong[")
        elif tok in ("</i>", "</b>"):
            out.append("]")
        elif tok == "\n":
            out.append("#linebreak()")
        elif tok.startswith("[^"):
            n = int(tok[2:-1])
            if n not in footnotes:
                raise PipelineError(f"footnote [^{n}] has no translated footnote text")
            used.add(n)
            # Set the counter explicitly: some books restart numbering per chapter.
            out.append(f"#counter(footnote).update({n - 1})"
                       f"#footnote[#h(0.3em){inline(footnotes[n], {}, set())}]")
        else:
            out.append(s(tok))
    return "".join(out)


def paragraph(seg: dict, en_text: str, metrics: dict, footnotes: dict, used: set) -> str:
    style = seg["style"]
    body = inline(en_text, footnotes, used)
    size = style["size"]
    text_args = f"size: {size}pt"
    # Original font families other than the main one (e.g. Helvetica letters)
    # map to a free equivalent: config pdf.font_map {"Helvetica": "Liberation Sans"}.
    for family, free in FONT_MAP.items():
        if family.lower() in style.get("font", "").lower():
            text_args += f', font: "{free}"'
            break
    if style["bold"]:
        text_args += ', weight: "bold"'
    if style["italic"]:
        text_args += ', style: "italic"'
    if style["align"] == "center":
        return (f"#align(center)[#par(first-line-indent: 0pt, justify: false)"
                f"[#text({text_args}, hyphenate: false)[{body}]]]")
    first = max(style["first_line_indent"], 0)
    left = max(style["left"], 0)
    if left > 5:
        # Hanging layout (bulleted lists): first line at `first`, rest at `left`.
        start = min(first, left)
        return (f"#pad(left: {start}pt)[#par(first-line-indent: 0pt, hanging-indent: "
                f"{max(left - first, 0)}pt)[#text({text_args})[{body}]]]")
    indent = first if first > 5 else 0
    return (f"#par(first-line-indent: (amount: {indent}pt, all: true))"
            f"[#text({text_args})[{body}]]")


def preamble(cfg: dict, metrics: dict, page: dict) -> str:
    pdf = cfg["pdf"]
    size = metrics["body_size"]
    top = metrics.get("top_margin", 71)
    bottom = metrics.get("bottom_margin", 72)
    leading = pdf["line_pitch_pt"] - size
    spacing = pdf["paragraph_pitch_pt"] - size
    fn_leading = pdf["footnote_pitch_pt"] - pdf["footnote_size_pt"]
    # Page number 40% into the bottom margin, raised for large numbers so the
    # glyphs stay clear of the bottom 30 pt (checked by check_pdf.py).
    descent = min(0.4 * bottom, bottom - 30 - 1.3 * pdf["page_number_size_pt"])
    return f"""// Generated by tools/build_pdf.py — do not edit by hand.
#set document(title: "{cfg['title_en']}", author: "Nessahan Alita")
#set page(
  width: {page['width']}pt, height: {page['height']}pt,
  margin: (left: {metrics['left']}pt, right: {page['width'] - metrics['right']}pt, top: {top}pt, bottom: {bottom}pt),
  footer: context align({pdf.get('page_number_align', 'center')}, text(size: {pdf['page_number_size_pt']}pt, counter(page).display())),
  footer-descent: {descent:.2f}pt,
)
#set text(font: "{pdf['font']}", size: {size}pt, lang: "en", region: "US",
  tracking: {pdf['tracking_pt']}pt, top-edge: 1em, bottom-edge: "baseline", hyphenate: true)
#set text(costs: (hyphenation: 150%, runt: 300%, widow: 300%, orphan: 300%))
#set par(justify: true, leading: {leading:.2f}pt, spacing: {spacing:.2f}pt)
#set footnote.entry(separator: line(length: {pdf['footnote_rule_pt']}pt, stroke: 0.5pt), indent: 0pt, gap: {fn_leading + 2}pt)
#show footnote.entry: set text(size: {pdf['footnote_size_pt']}pt)
#show footnote.entry: set par(leading: {fn_leading:.2f}pt, first-line-indent: 0pt)
#show heading: it => block(above: {spacing:.2f}pt, below: {spacing:.2f}pt, width: 100%,
  align({metrics.get('heading_align', 'center')}, par(justify: false, text(size: {size}pt, weight: "bold", hyphenate: false, it.body))))
"""


def front_matter(segments, en, layout, metrics, footnotes, used) -> str:
    """Chapter 00: reproduce the original vertical positions page by page."""
    out, page, prev_bottom = [], None, None
    top = metrics.get("top_margin", 71)
    for seg in segments:
        if seg["type"] == "footnote":
            continue
        lines = layout[seg["id"]]["lines"]
        y0, y1 = lines[0]["bbox"][1], lines[-1]["bbox"][3]
        if lines[0]["page"] != page:
            if page is not None:
                out.append("#pagebreak()")
            page, prev_bottom = lines[0]["page"], top
        gap = max(y0 - prev_bottom, 0)
        out.append(f"#v({gap:.1f}pt, weak: false)")
        style = dict(seg["style"])
        if seg["type"] == "heading":
            style["align"] = "center"
        body = paragraph({"style": style}, en[seg["id"]], metrics, footnotes, used)
        out.append(f"#block(width: 100%, spacing: 0pt)[{body}]")
        prev_bottom = y1
    out.append("#pagebreak()")
    return "\n".join(out)


def chapter_body(segments, en, layout, metrics, footnotes, used) -> str:
    out = []
    top = metrics.get("top_margin", 71)
    run_in = ""  # emphasized sentence misdetected as a heading, joined to the next paragraph
    table = []   # pending table_row segments (cells separated by "¦")

    def flush_table():
        """Rows whose first cell is empty continue the previous row: each group
        becomes one table row, with its second-column entries stacked."""
        if not table:
            return
        groups = []
        for seg, text in table:
            cells = [c.strip() for c in text.split("¦")]
            if cells[0] or not groups:
                groups.append([[c] if c else [] for c in cells])
            else:
                for k, c in enumerate(cells[1:], 1):
                    if c:
                        groups[-1][k].append(c)
        style = table[0][0]["style"]
        cols = style.get("columns", [metrics["left"]])
        widths = [f"{cols[k + 1] - cols[k]:.0f}pt" for k in range(len(cols) - 1)] + ["auto"]
        font = ""
        for family, free in FONT_MAP.items():
            if family.lower() in style.get("font", "").lower():
                font = f', font: "{free}"'
        cells = []
        for group in groups:
            for parts in group:
                body = "#linebreak()".join(inline(x, footnotes, used) for x in parts)
                cells.append(f"[#par(first-line-indent: 0pt, justify: false)"
                             f"[#text(size: {style['size']}pt{font})[{body}]]]")
        out.append(f"#table(columns: ({', '.join(widths)}), stroke: 0.5pt, "
                   f"inset: (x: 5pt, y: 6pt), {', '.join(cells)})")
        table.clear()
    for i, seg in enumerate(segments):
        if seg["type"] == "footnote":
            continue
        text = en[seg["id"]]
        if seg["type"] == "heading" and i > 0 and seg["style"]["size"] < metrics["body_size"] - 0.5:
            # Real headings are never smaller than the body text: this is a bold
            # sentence that continues in the next segment (e.g. 32-0148 of
            # como-lidar-com-mulheres-2008).
            print(f"run-in {seg['id']}: heading smaller than body text, joined to the next paragraph")
            run_in = (f"<b>{text}</b>" if seg["style"].get("bold") else text) + " "
            continue
        if run_in and seg["type"] != "heading":
            text, run_in = run_in + text, ""
        if re.fullmatch(r"\s*[.,;:]\s*", strip_markup(text)):
            # Typographic artifact: a single stray punctuation mark alone in the
            # original. Separators such as "*****" are kept.
            print(f"skipped {seg['id']}: stray punctuation ({text!r})")
            continue
        if seg["type"] == "table_row":
            table.append((seg, text))
            continue
        flush_table()
        if seg["type"] == "heading":
            first_line = layout[seg["id"]]["lines"][0]
            if i == 0 and first_line["bbox"][1] < top + 30:
                out.append("#pagebreak(weak: true)")
            out.append(f"#heading(level: {1 if i == 0 else 2})[{inline(text, footnotes, used)}]")
        else:
            out.append(paragraph(seg, text, metrics, footnotes, used))
    flush_table()
    return "\n\n".join(out)


def glossary_entries(slug: str, book_text: str) -> list[dict]:
    """The glossary concepts used in this book, sorted, for the appendix of the
    English edition (PDF and EPUB).

    Every concept/style entry that occurs in the book must have English notes
    (display_en, display_pt, note_en); otherwise the build fails, so no future
    book can ship without its glossary."""
    from common import GLOSSARY_FILE
    entries = load_json(GLOSSARY_FILE)["entries"]
    used, missing = [], []
    for e in entries:
        if e["category"] not in ("concept", "style"):
            continue
        books = e.get("books", ["*"])
        if "*" not in books and slug not in books:
            continue
        if not forms_regex(e["match_pt"]).search(book_text):
            continue
        if not e.get("note_en"):
            missing.append(e["term_pt"])
            continue
        used.append(e)
    if missing:
        raise PipelineError("glossary concepts used in this book have no English note "
                            f"(add display_en/display_pt/note_en in glossary.json): {missing}")
    used.sort(key=lambda e: e["display_en"].lower())
    return used


def glossary_appendix(slug: str, book_text: str) -> str:
    """Appendix for the English edition: the glossary concepts used in this book."""
    used = glossary_entries(slug, book_text)
    out = ["#pagebreak(weak: true)", "#heading(level: 1)[Glossary]",
           f"#par(first-line-indent: 0pt)[#emph[{s(GLOSSARY_INTRO)}]]"]
    for e in used:
        out.append(f"#par(first-line-indent: 0pt, hanging-indent: 18pt)"
                   f"[#strong[{s(e['display_en'])}] {s('(')}#emph[{s(e['display_pt'])}]{s(') — ' + e['note_en'])}]")
    print(f"glossary appendix: {len(used)} terms")
    return "\n\n".join(out)


def build(slug: str, draft: bool) -> None:
    cfg = load_book_config(slug)
    if "pdf" not in cfg or "title_en" not in cfg:
        raise PipelineError(f"config/books/{slug}.json needs 'title_en' and a 'pdf' section")
    book = load_json(WORK_DIR / slug / "book.json")
    metrics = dict(book["metrics"])
    page = load_json(cfg["_extracted_path"] / "metadata.json")["pages"][0]
    glossary = load_glossary(slug)

    FONT_MAP.clear()
    FONT_MAP.update(cfg["pdf"].get("font_map", {}))
    # Chapter headings follow the original's predominant alignment.
    aligns = []
    for chapter in chapter_ids(slug)[1:]:
        first = load_json(WORK_DIR / slug / "chapters" / f"{chapter}.json")["segments"][0]
        if first["type"] == "heading":
            aligns.append(first["style"]["align"])
    metrics["heading_align"] = "center" if aligns.count("center") >= len(aligns) / 2 else "left"
    parts = [preamble(cfg, metrics, page)]
    book_text = []
    for chapter in chapter_ids(slug):
        try:
            result = check_chapter(slug, chapter, glossary)
        except PipelineError:
            if not draft:
                raise
            result = {"complete": False, "errors": ["no translation file"],
                      "segments_translated": 0, "segments_total": "?"}
        if not result["complete"] or result["errors"]:
            msg = (f"chapter {chapter}: {result['segments_translated']}/{result['segments_total']} "
                   f"translated, {len(result['errors'])} QA errors")
            if not draft:
                raise PipelineError(msg + " (fix, or use --draft)")
            print(f"WARNING: {msg}")
        source = load_json(WORK_DIR / slug / "chapters" / f"{chapter}.json")["segments"]
        layout = load_json(WORK_DIR / slug / "chapters" / f"{chapter}.layout.json")
        en_path = TRANSLATIONS_DIR / slug / f"{chapter}.en.md"
        en = {e["id"]: e["text"] for e in parse_marked_md(en_path)} if en_path.exists() else {}
        # Draft builds fall back to the source text so the layout can be checked.
        en = {s_["id"]: en.get(s_["id"]) or s_["text"] for s_ in source}
        footnotes = {s_["fn"]: en[s_["id"]] for s_ in source if s_["type"] == "footnote"}
        book_text += [strip_markup(s_["text"]) for s_ in source]
        used = set()
        if chapter == "00":
            parts.append(front_matter(source, en, layout, metrics, footnotes, used))
        else:
            parts.append(chapter_body(source, en, layout, metrics, footnotes, used))
        unused = set(footnotes) - used
        if unused:
            raise PipelineError(f"chapter {chapter}: footnotes never referenced: {sorted(unused)}")

    # Every English edition ends with its glossary (config: pdf.glossary_appendix).
    if cfg["pdf"].get("glossary_appendix", True):
        parts.append(glossary_appendix(slug, " ".join(book_text)))

    out_dir = OUTPUT_DIR / slug
    typ = out_dir / "build" / "book.typ"
    write_text_atomic(typ, "\n\n".join(parts) + "\n")
    pdf_path = out_dir / f"{slug}-en.pdf"
    try:
        import typst
    except ImportError:
        raise PipelineError("Typst is not installed: pymupdf-venv\\Scripts\\pip install typst")
    tmp = pdf_path.with_suffix(".pdf.tmp")
    try:
        typst.compile(str(typ), output=str(tmp), root=str(ROOT),
                      font_paths=[str(ROOT / cfg["pdf"]["font_dir"])], ignore_system_fonts=True)
    except Exception as exc:  # typst raises its own error type with the diagnostics
        raise PipelineError(f"Typst compilation failed:\n{exc}")
    tmp.replace(pdf_path)
    print(f"PDF: {pdf_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("slug")
    parser.add_argument("--draft", action="store_true")
    args = parser.parse_args()
    try:
        build(args.slug, args.draft)
    except PipelineError as exc:
        fail(str(exc))


if __name__ == "__main__":
    sys.exit(main())
